import { writeFileSync } from "node:fs";
import { ADMIN_LANGUAGES } from "../admin/src/app/languages.ts";
import english from "../admin/src/app/locales/en.ts";

// The App is one HTML file. Include only the Admin labels shared by its fields and operations.
const interactionKeys = Object.keys(english).filter(key => key.startsWith("interaction."));
const fields = {
  emptyOption: "entryEdit.emptyOption",
  clearOption: "entryEdit.clearOption",
  chooseOption: "entryEdit.chooseOption",
  boolean: "entryEdit.boolean",
  dateTimeSelect: "entryEdit.dateTime.select",
  dateTimeTime: "entryEdit.dateTime.time",
  removeItem: "entryEdit.removeItem",
  addItem: "entryEdit.addItem",
};
const catalog = {};
for (const { value } of ADMIN_LANGUAGES) {
  const { default: locale } = await import(`../admin/src/app/locales/${value}.ts`);
  const t = key => locale[key] ?? english[key];
  catalog[value] = {
    viewFailed: t("common.failedToLoad"),
    fields: Object.fromEntries(
      Object.entries(fields)
        .filter(([, key]) => value === "en" || locale[key] !== undefined)
        .map(([name, key]) => [name, t(key)]),
    ),
    interaction: {
      ...Object.fromEntries(
        interactionKeys
          .filter(key => value === "en" || locale[key] !== undefined)
          .map(key => [key.slice("interaction.".length), t(key)]),
      ),
      cancel: locale["interaction.cancel"] ?? t("oauth.consent.deny"),
      close: locale["interaction.close"] ?? t("common.close"),
    },
  };
}
writeFileSync(
  new URL("../admin/src/mcp-app/admin-labels.generated.ts", import.meta.url),
  `// Generated by emit-mcp-labels.mjs.\nexport const adminLabels = ${JSON.stringify(catalog)} as const;\n`,
);
