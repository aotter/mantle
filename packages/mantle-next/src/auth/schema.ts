/**
 * DDL for the tables Better Auth itself declares for these options (core tables, plugins, additional fields, renamed
 * models/fields, indexes), read from its own `getSchema`, so nothing about the shape is re-decided here. Column types
 * match what the native adapters store: on SQLite (D1, bun:sqlite) dates are ISO text and booleans are 0/1; on
 * PostgreSQL they are timestamptz and boolean. Deterministic: same options, same statements, in dependency order.
 */
import type { BetterAuthOptions } from "@better-auth/core";
import { getAuthTables, type DBFieldAttribute } from "@better-auth/core/db";
import { getSchema } from "better-auth/db";

export type AuthDialect = "sqlite" | "postgres";

const ident = (name: string) => name.split(".").map(part => `"${part.replaceAll('"', '""')}"`).join(".");

function columnType(field: DBFieldAttribute, dialect: AuthDialect): string {
  const pg = dialect === "postgres";
  if (Array.isArray(field.type)) return "text";
  switch (field.type) {
    case "number": return field.bigint ? "bigint" : "integer";
    case "boolean": return pg ? "boolean" : "integer";
    case "date": return pg ? "timestamptz" : "text";
    case "json": return pg ? "jsonb" : "text";
    // The factory stores arrays as JSON text (supportsArrays: false); Bun.SQL would encode that text into jsonb as a JSON string.
    case "string[]": case "number[]": return "text";
    default: return "text";
  }
}

/**
 * Better Auth's name for a field-level index (`<table>_<column>_idx`; past PostgreSQL's 63-byte identifier limit the middle is
 * cut and an FNV-1a hash of the full name is spliced in). Its helper lives in `@better-auth/core/db/internal`, which is not public
 * API, so the same rule is restated here: a database already migrated by Better Auth's CLI keeps matching names, and
 * `IF NOT EXISTS` skips the index instead of duplicating it.
 */
export function fieldIndexName(table: string, column: string): string {
  const full = `${table}_${column}_idx`;
  if (new TextEncoder().encode(full).length <= 63) return full;
  let hash = 2166136261;
  for (let i = 0; i < full.length; i++) hash = Math.imul(hash ^ full.charCodeAt(i), 16777619);
  const suffix = `_${(hash >>> 0).toString(16).padStart(8, "0")}_idx`;
  return full.slice(0, 63 - suffix.length) + suffix;
}

type Tables = [string, ReturnType<typeof getSchema>[string]][];

/** Better Auth's own `order`, then referenced tables before the tables that reference them. */
function orderedTables(options: BetterAuthOptions): Tables {
  const byOrder = Object.entries(getSchema(options)).filter(([, table]) => !table.disableMigrations).sort((a, b) => a[1].order - b[1].order);
  const ordered: Tables = [];
  const place = (entry: Tables[number], visiting: Set<string>) => {
    if (ordered.includes(entry) || visiting.has(entry[0])) return;
    visiting.add(entry[0]);
    for (const field of Object.values(entry[1].fields)) {
      const target = byOrder.find(([name]) => name === field.references?.model);
      if (target) place(target, visiting);
    }
    ordered.push(entry);
  };
  for (const entry of byOrder) place(entry, new Set());
  return ordered;
}

/** Table names in creation order; drop them in reverse. */
export const authTableNames = (options: BetterAuthOptions): string[] => orderedTables(options).map(([name]) => name);

export function authSchemaSql(options: BetterAuthOptions, dialect: AuthDialect): string[] {
  const generateId = options.advanced?.database?.generateId;
  const idType = generateId === "serial" ? "integer" : generateId === "uuid" && dialect === "postgres" ? "uuid" : "text";
  const idColumn = generateId === "serial" ? (dialect === "postgres" ? "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "integer PRIMARY KEY") : `${idType} PRIMARY KEY NOT NULL${idType === "uuid" ? " DEFAULT gen_random_uuid()" : ""}`;
  // `references.field` is a logical field name; the column it points at may be renamed (`fields: { email: "email_address" }`).
  const logical = Object.values(getAuthTables(options));
  const referenced = (ref: { model: string; field: string }) => logical.find(t => t.modelName === ref.model)?.fields[ref.field]?.fieldName ?? ref.field;
  const statements: string[] = [];
  const indexes: string[] = [];
  for (const [name, table] of orderedTables(options)) {
    const columns = [`${ident("id")} ${idColumn}`];
    for (const [column, field] of Object.entries(table.fields)) {
      if (column === "id") continue;
      const type = field.references?.field === "id" ? (generateId === "serial" ? "integer" : idType) : columnType(field, dialect);
      columns.push([
        ident(column), type,
        field.required !== false && "NOT NULL",
        field.unique && "UNIQUE",
        field.references && `REFERENCES ${ident(field.references.model)}(${ident(referenced(field.references))}) ON DELETE ${(field.references.onDelete ?? "cascade").toUpperCase()}`,
      ].filter(Boolean).join(" "));
      if (field.index && !field.unique) indexes.push(`CREATE INDEX IF NOT EXISTS ${ident(fieldIndexName(name, column))} ON ${ident(name)} (${ident(column)})`);
    }
    statements.push(`CREATE TABLE IF NOT EXISTS ${ident(name)} (${columns.join(", ")})`);
    for (const index of table.indexes ?? []) indexes.push(`CREATE ${index.unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${ident(index.name)} ON ${ident(name)} (${index.columns.map(ident).join(", ")})`);
  }
  return [...statements, ...indexes];
}
