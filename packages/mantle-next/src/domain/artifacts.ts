/** Ownership marker shared by generation and the CLI's stale-file check. */
export const GENERATED = "Generated by mantle generate — do not edit.";
export function generatedFiles(files: Readonly<Record<string, string>>): Record<string, string> {
  return Object.fromEntries(Object.entries(files).map(([name, source]) => [name,
    source.startsWith(`// ${GENERATED}\n`) || source.startsWith(`-- ${GENERATED}\n`) ? source : `${name.endsWith(".sql") ? "--" : "//"} ${GENERATED}\n${source}`]));
}
