import { indexDefinitions } from "../core/sql/storage.js";
import { q } from "../core/sql/ast.js";
/** Build-time initial PostgreSQL DDL; applications own migrations. */
import { checkShapeProblem, notNullColumns, storageColumns, type SqlNode } from "../spec/domain/index.js";
import type { StorageSchema } from "../core/dialect.js";
import { pgType } from "./codec.js";
import { print, typed } from "./print.js";
import { fnv } from "../spec/domain/service/PlanFingerprint.js";

// PostgreSQL identifiers are limited to 63 bytes; retain the existing deterministic names.
const ident = (n: string) => (new TextEncoder().encode(n).length <= 63 ? n : `${n.slice(0, 50)}_${fnv(n)}`);
interface Column {
  readonly name: string;
  readonly type: string;
  readonly native: boolean;
}

function columns(s: StorageSchema): Column[] {
  return [
    ...(s.scope ? [{ name: s.scope, type: "text", native: true }] : []),
    ...(s.publishing
      ? [
          { name: "status", type: "text", native: true },
          { name: "published_at", type: "timestamptz", native: false },
        ]
      : []),
    ...Object.entries(s.fields)
      .filter(([f]) => f !== s.scope)
      .flatMap(([f, ty]): Column[] =>
        ty === "geo"
          ? [
              { name: `${f}_lat`, type: "float8", native: false },
              { name: `${f}_lng`, type: "float8", native: false },
            ]
          : [{ name: f, type: pgType(ty), native: false }],
      ),
  ];
}

function indexes(name: string, s: StorageSchema) {
  return indexDefinitions(name, s).map(i => ({
    ...i,
    name: ident(i.name),
    sql: `CREATE ${i.unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${q(ident(i.name))} ON ${q(name)} (${i.columns.map(q).join(", ")})`,
  }));
}

/** A check's expression as PostgreSQL prints it, over the row's own columns. */
function checkText(expr: SqlNode, s: StorageSchema): string {
  const problem = checkShapeProblem(expr, storageColumns(s));
  if (problem) throw new Error(problem);
  return print(
    typed(
      {
        SelectStmt: {
          targetList: [{ ResTarget: { val: expr } }],
          limitOption: "LIMIT_OPTION_DEFAULT",
          op: "SETOP_NONE",
        },
      },
      {},
    ),
  ).replace(/^SELECT\s+/i, "");
}

/**
 * Newly created text columns retain C for compatibility (#1400). Existing columns keep their actual collation;
 * paging and indexes follow it (ADR-0039). A future default change is a separate compatibility decision,
 * and any existing-column/index migration belongs to the operator (ADR-0040).
 */
const ddlType = (type: string) => (type === "text" ? 'text COLLATE "C"' : type);
/** `notNull`: the columns the initial artifact (not convergence) also declares NOT NULL. */
const createTable = (name: string, s: StorageSchema, notNull: ReadonlySet<string> = new Set()) =>
  `CREATE TABLE ${q(name)} (${[
    "_rid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    `id ${ddlType("text")} NOT NULL UNIQUE`,
    "version int8 NOT NULL DEFAULT 1",
    "created_at timestamptz NOT NULL",
    "updated_at timestamptz NOT NULL DEFAULT now()",
    `author_id ${ddlType("text")}`,
    ...columns(s).map(
      c =>
        `${q(c.name)} ${ddlType(c.type)}${c.name === "status" ? " NOT NULL DEFAULT 'draft'" : c.native || notNull.has(c.name) ? " NOT NULL" : ""}`,
    ),
  ].join(", ")})`;

/** Build-time initial schema artifact. Applying or migrating it is the application's responsibility. */
export function initialStorageSql(plan: Readonly<Record<string, StorageSchema>>): readonly string[] {
  return Object.entries(plan).flatMap(([name, schema]) => [
    // No Admin surface is selected by this SQL-only artifact; emit authored indexes only.
    createTable(name, schema, notNullColumns(schema)),
    ...indexes(name, schema).map(i => i.sql),
    ...(schema.checks ?? []).map(
      (check, i) =>
        `ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(ident(`_mantle_chk_${name}_${i}`))} CHECK (${checkText(check, schema)})`,
    ),
  ]);
}
