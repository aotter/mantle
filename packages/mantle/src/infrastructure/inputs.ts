/** `mantle generate` fingerprints its inputs next to the output; `mantle bundle` refuses output whose inputs changed since. */
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

export const INPUTS_FILE = ".mantle-inputs.json";
/** The installed `@aotter/mantle` version (dist/infrastructure → package root). */
const MANTLE_VERSION = (JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8")) as { version: string }).version;
const digest = (path: string) => existsSync(path) ? createHash("sha256").update(readFileSync(path)).digest("hex") : null;

/** The manifests and option modules (`--auth`, `--site`, `--admin-extensions`) one generate run read, by path relative to its output. */
export function inputsFingerprint(destination: string, paths: readonly string[]): string {
  const inputs = Object.fromEntries(paths.map(path => [relative(resolve(destination), resolve(path)).replaceAll("\\", "/"), digest(path)]));
  return JSON.stringify({ mantle: MANTLE_VERSION, inputs }, null, 2) + "\n";
}

/** Why the generated output that holds `generatedModule` no longer matches its inputs (empty when it does, or when it has no fingerprint). */
export function staleInputs(generatedModule: string): string[] {
  const directory = dirname(generatedModule), file = resolve(directory, INPUTS_FILE);
  if (!existsSync(file)) return [];
  const recorded = JSON.parse(readFileSync(file, "utf8")) as { mantle: string; inputs: Record<string, string | null> };
  const stale = recorded.mantle === MANTLE_VERSION ? [] : [`generated by Mantle ${recorded.mantle}, building with ${MANTLE_VERSION}`];
  for (const [path, hash] of Object.entries(recorded.inputs)) if (digest(resolve(directory, path)) !== hash) stale.push(`${relative(process.cwd(), resolve(directory, path))} changed`);
  return stale;
}

/** Better Auth roles an app declares beyond `admin` and `user` (`<name>: ac.newRole(...)`), for a one-line design note. */
export function extraRoles(source: string): string[] {
  return [...source.matchAll(/["']?([A-Za-z][\w-]*)["']?\s*:\s*ac\.newRole\(/g)].map(m => m[1]!).filter(role => role !== "admin" && role !== "user");
}

/** Better Auth tables an app's own code queries with SQL (`FROM "user"`, `JOIN session` ...), for a one-line note. */
export function authTableSql(source: string): string[] {
  return [...new Set([...source.matchAll(/\b(?:FROM|JOIN|UPDATE|INTO)\s+"?(user|session|account|verification)"?(?=[\s;),`'"]|$)/gi)].map(m => m[1]!.toLowerCase()))];
}
