import { expect, test } from "bun:test";
import { generateFromSources } from "../src/infrastructure/generate.js";

const manifest = (kind: string, name: string, spec: object) => ({ sourceId: name + ".json", text: JSON.stringify({ apiVersion: "cms.mantle.aotter.net/v2", kind, metadata: { name }, spec }) });
const sources = [
  manifest("Schema", "tasks", { title: "Tasks", lifecycle: "operational", scope: "owner = auth.uid()", indexes: [["owner", "createdAt", "id"]], schema: { type: "object", properties: { owner: { type: "string" }, title: { type: "string" }, priorityLevel: { type: "integer" }, note: { type: "string" } }, required: ["owner", "title"] } }),
  manifest("View", "task-board", { surface: "admin", input: { type: "object", properties: { q: { type: "string" } } }, sql: "SELECT t.id, t.title FROM tasks t ORDER BY t.id" }),
  manifest("View", "public-tasks", { surface: "public", sql: "SELECT id, title FROM tasks ORDER BY id" }),
  manifest("Procedure", "mark-done", { requires: { auth: { all: ["ctx.admin"] } }, input: { type: "object", properties: { entryId: { type: "string" }, expectedVersion: { type: "integer" } }, required: ["entryId", "expectedVersion"] }, output: { type: "object" }, handler: { sql: "UPDATE tasks SET note = 'done' WHERE id = input.entryId AND version = input.expectedVersion" } }),
  manifest("Trigger", "mark-done-mcp", { source: { kind: "mcp", surface: "admin" }, target: { procedure: "mark-done" } }),
];

async function files(admin: boolean): Promise<Readonly<Record<string, string>>> {
  const result = await generateFromSources({ target: "bun-sqlite", admin, sources: { sources } });
  if (!result.ok) throw Error(JSON.stringify(result.diagnostics));
  return result.files;
}

test("--admin emits generated/admin-client.ts: typed names, tools and bound hooks, with types only from generated modules", async () => {
  const client = (await files(true))["admin-client.ts"]!;
  expect(client).toStartWith("// Generated by mantle generate");
  // admin Views only; the public View is not an Admin name
  expect(client).toContain('readonly "task-board": { readonly input: { readonly "q"?: string;  }; readonly row: View0Row }');
  expect(client).not.toContain("public-tasks");
  expect(client).toContain('import type { WireRow as View0Row } from "./views/task-board.js";');
  // an entry's data keeps declared names and has no scope field
  expect(client).toContain('readonly "priorityLevel"?: number');
  expect(client).not.toContain('"owner"');
  // an operation's input is what its route validates; its tool is the admin MCP tool
  expect(client).toContain('readonly "mark-done": { readonly input: { readonly "entryId": string; readonly "expectedVersion": number;  }; readonly output: Output }');
  expect(client).toContain('views: { "task-board": { tool: "task_board" } }, operations: { "mark-done": { tool: "mark_done" } }');
  // browser-only: nothing from the Worker is imported as a value
  const imports = client.split("\n").filter(line => line.startsWith("import "));
  expect(imports.filter(line => !line.startsWith("import type "))).toEqual(['import { createAdminHooks } from "@aotter/mantle-admin/hooks";']);
  expect(client).not.toMatch(/from "\.\/(?:generated|admin-descriptors|admin-bindings)/);
  for (const hook of ["useView", "useEntries", "useEntry", "useOperation", "useCollectionTotal", "useMe"]) expect(client).toContain(`export const ${hook} = hooks.${hook};`);
});

test("without --admin there is no admin-client.ts", async () => {
  expect(Object.keys(await files(false))).not.toContain("admin-client.ts");
});
