import { readFileSync, writeFileSync } from "node:fs";
import { ADMIN_LANGUAGES } from "../../mantle-admin/admin/src/app/languages.ts";
import english from "../../mantle-admin/admin/src/app/locales/en.ts";

// Select the auth page's copy at build time. Core serves it without loading Admin, React or the UI package.
const keys = {
  language: "preferences.language",
  appearance: "preferences.appearance",
  system: "preferences.system",
  light: "preferences.light",
  dark: "preferences.dark",
  eyebrow: "oauth.consent.eyebrow",
  heading: "oauth.consent.heading",
  body: "oauth.consent.body",
  returnsTo: "oauth.consent.redirect",
  scopes: "oauth.consent.scopes",
  offline: "oauth.consent.offline",
  approve: "oauth.consent.approve",
  deny: "oauth.consent.deny",
  invalid: "oauth.consent.invalidTitle",
  invalidBody: "oauth.consent.invalidBody",
  apps: "oauth.connectedApps",
  appsBody: "oauth.apps.body",
  empty: "oauth.apps.empty",
  revoke: "oauth.apps.revoke",
};
const messages = {};
for (const { value, htmlLang, nativeLabel, direction } of ADMIN_LANGUAGES) {
  const { default: locale } = await import(`../../mantle-admin/admin/src/app/locales/${value}.ts`);
  messages[value] = {
    lang: htmlLang,
    nativeLabel,
    dir: direction,
    ...Object.fromEntries(
      Object.entries(keys).map(([name, key]) => {
        if (!english[key]) throw new Error(`Missing Admin message: ${key}`);
        return [name, locale[key] ?? english[key]];
      }),
    ),
  };
}
const tokens = readFileSync(new URL("../../mantle-ui/src/kit/styles/tokens.css", import.meta.url), "utf8");
const dark = /:where\(:root\[data-theme="dark"\]\)\s*\{([^}]+)\}/u.exec(tokens)?.[1];
if (!dark) throw new Error("Missing mantle-ui dark tokens");
writeFileSync(
  new URL("../src/auth/consent-presentation.generated.ts", import.meta.url),
  `// Generated by emit-auth-presentation.mjs.\nexport const messages = ${JSON.stringify(messages)} as const;\nexport const tokens = ${JSON.stringify(tokens)};\nexport const systemDark = ${JSON.stringify(`@media(prefers-color-scheme:dark){:root[data-theme=system]{${dark}}}`)};\n`,
);
